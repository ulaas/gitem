"""Writes THIRD-PARTY-NOTICES.md: every crate that ships in gitem, on every platform, with its
license and where it comes from. Development-only crates (tests, benchmarks) are left out.

    python scripts/third-party-notices.py
"""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

out = subprocess.run(
    ["cargo", "tree", "-p", "gitem", "-e", "normal,build", "--target", "all", "--prefix", "none", "--locked", "--format", "{p}\t{l}\t{r}"],
    cwd=ROOT, capture_output=True, text=True, check=True,
).stdout

crates = {}
for line in out.splitlines():
    parts = [p.replace(" (*)", "") for p in line.split("\t")]
    if len(parts) < 2:
        continue
    pkg = parts[0].replace(" (*)", "").strip()
    if "(" in pkg and ("\\" in pkg or "/" in pkg):  # the workspace's own crates
        continue
    name, _, version = pkg.partition(" ")
    crates[(name, version)] = (parts[1].strip() or "see its repository", parts[2].strip() if len(parts) > 2 else "")

rows = "\n".join(f"| {n} | {v} | {lic} | {repo} |" for (n, v), (lic, repo) in sorted(crates.items(), key=lambda kv: (kv[0][0].lower(), kv[0][1])))

text = f"""# Third-party notices

gitem itself is under the MIT License (see [LICENSE](LICENSE)). It's built on the open-source crates
below, each under its own license, which applies to that crate. Where a crate offers a choice
("MIT OR Apache-2.0"), gitem uses it under the MIT License where that's one of the choices.

## Fonts embedded in the app

egui, the interface toolkit, builds these fonts into the binary (crate `epaint_default_fonts`):

- **Ubuntu Light**, under the Ubuntu Font License 1.0.
- **Hack**, under the MIT License, with parts from DejaVu (public domain) and Bitstream Vera (the Bitstream Vera License).
- **Noto Emoji**, under the SIL Open Font License 1.1.
- **emoji-icon-font**, under the MIT License.

The interface icons are [Phosphor Icons](https://phosphoricons.com), under the MIT License, through
the `egui-phosphor` crate. On Windows, macOS and Linux gitem also uses fonts already installed on the
system, for symbols and non-Latin text; those aren't distributed with it.

## Syntax highlighting

The syntax definitions and colour themes built in through `syntect` come from the
[sublimehq/Packages](https://github.com/sublimehq/Packages) repository and from each theme's own
project, under their authors' licenses; `syntect` itself is under the MIT License.

## Crates

Generated by `scripts/third-party-notices.py` from `cargo tree`: {len(crates)} crates.

| Crate | Version | License | Source |
| --- | --- | --- | --- |
{rows}
"""
(ROOT / "THIRD-PARTY-NOTICES.md").write_text(text, encoding="utf-8", newline="\n")
print(f"{len(crates)} crates")
